#!/usr/bin/env node
/**
 * Regenerates plugins/CarbonArc/CarbonArcFonts.css from the woff2 files in
 * plugins/CarbonArc/fonts/.
 *
 * Why the fonts are embedded instead of linked: Stash serves a plugin's
 * stylesheets concatenated at /plugin/<id>/css and exposes no route for other
 * files in the plugin directory, so url("fonts/x.woff2") resolves to
 * /plugin/<id>/fonts/x.woff2 and 404s. A data URI has no path to resolve, so it
 * works whichever way the stylesheet is delivered (and behind a reverse-proxy
 * prefix, too).
 *
 * Run after replacing a woff2 file:
 *   node scripts/build_fonts_css.mjs
 *
 * Stdlib only, like tests/.
 */
import { readFileSync, writeFileSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pluginDir = join(root, "plugins", "CarbonArc");
const fontDir = join(pluginDir, "fonts");
const outFile = join(pluginDir, "CarbonArcFonts.css");

const FACES = [
  { file: "ibm-plex-sans-latin.woff2", family: "IBM Plex Sans", weight: "100 700" },
  { file: "ibm-plex-mono-400-latin.woff2", family: "IBM Plex Mono", weight: "400" },
  { file: "ibm-plex-mono-500-latin.woff2", family: "IBM Plex Mono", weight: "500" },
];

const header = `/*
 * Carbon Arc — bundled type.
 *
 * GENERATED by scripts/build_fonts_css.mjs from fonts/*.woff2. Do not edit by
 * hand; rerun the script after replacing a font file.
 *
 * The fonts are data URIs because Stash serves a plugin's CSS as one
 * concatenated response at /plugin/<id>/css and has no route for other files
 * in the plugin directory: a relative url() there 404s. Both faces are the
 * latin subset only — anything outside it falls through to the stack in
 * --ca-font, which is the system UI font.
 *
 * IBM Plex is licensed under the SIL Open Font License 1.1; the licence text
 * travels with the source files in fonts/OFL.txt.
 */

`;

const blocks = FACES.map(({ file, family, weight }) => {
  const bytes = readFileSync(join(fontDir, file));
  const base64 = bytes.toString("base64");
  return (
    `/* ${file} — ${(statSync(join(fontDir, file)).size / 1024).toFixed(1)} KB */\n` +
    `@font-face {\n` +
    `  font-family: "${family}";\n` +
    `  font-style: normal;\n` +
    `  font-weight: ${weight};\n` +
    `  font-display: swap;\n` +
    `  src: url("data:font/woff2;base64,${base64}") format("woff2");\n` +
    `}\n`
  );
}).join("\n");

writeFileSync(outFile, header + blocks, "utf8");

const total = statSync(outFile).size;
console.log("wrote " + outFile + " (" + (total / 1024).toFixed(1) + " KB)");
